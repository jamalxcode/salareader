const { chromium } = require('playwright');
const T = process.argv[2];
(async () => {
  const b = await chromium.launch(); const errs = [];
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
  await ctx.route('**/*', (r) => { const u = r.request().url(); if (u.includes('dompurify')) return r.fulfill({ path: T + '/pw/node_modules/dompurify/dist/purify.min.js', contentType: 'text/javascript', headers: { 'access-control-allow-origin': '*' } }); if (u.includes('transformers')) return r.fulfill({ path: T + '/pw/fake-tf.js', contentType: 'text/javascript', headers: { 'access-control-allow-origin': '*' } }); return u.startsWith('http://localhost') ? r.continue() : r.abort(); });
  const p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('http://localhost:8770/?debug#/smart/topic%3Aai'); await p.waitForSelector('article.entry');
  await p.click('article.entry .line'); await p.waitForSelector('.body .actions');
  await p.click('.body [data-act="digdeeper"]'); await p.waitForSelector('.inv-head'); await p.waitForTimeout(300);
  const m = () => p.evaluate(() => { const r = (s) => Math.round(document.querySelector(s).getBoundingClientRect().width); return { main: r('main'), panel: r('#invPanel'), text: document.querySelector('.body .content') ? r('.body .content') : '-', overflow: document.documentElement.scrollWidth - innerWidth }; });
  console.log('start', await m());
  const box = await p.locator('#invResizer').boundingBox(); console.log('handle', box);
  const x = box.x + box.width / 2, y = box.y + 300;
  await p.mouse.move(x, y); await p.mouse.down(); await p.mouse.move(x - 150, y, { steps: 8 }); await p.mouse.up(); await p.waitForTimeout(100);
  console.log('dragged 150 left', await m());
  await p.screenshot({ path: `${T}/shot-resize.png` });
  await p.mouse.move(x - 150, y); await p.mouse.down(); await p.mouse.move(x - 1200, y, { steps: 8 }); await p.mouse.up(); await p.waitForTimeout(100);
  console.log('dragged far left (max)', await m());
  await p.reload(); await p.waitForSelector('article.entry'); await p.waitForTimeout(500);
  await p.click('#sidebar [data-inv]'); await p.waitForSelector('.inv-head'); await p.waitForTimeout(200);
  console.log('after reload (kept)', await m());
  await p.focus('#invResizer'); await p.keyboard.press('End'); console.log('End key (min)', await m());
  await p.keyboard.press('ArrowLeft'); console.log('ArrowLeft +24', await m());
  await p.dblclick('#invResizer'); console.log('dblclick reset', await m());
  await p.setViewportSize({ width: 1000, height: 700 }); await p.waitForTimeout(200);
  await p.focus('#invResizer'); await p.keyboard.press('Home'); console.log('1000px, max', await m());
  await p.setViewportSize({ width: 390, height: 800 }); await p.waitForTimeout(200);
  console.log('phone handle visible:', await p.isVisible('#invResizer'));
  console.log('errors', errs); await b.close();
})();
